-- Snowflake DDL for e-commerce analytics star schema
-- Database / warehouse names match SnowflakeAdapter defaults.

CREATE DATABASE IF NOT EXISTS ECOM_ANALYTICS;
CREATE SCHEMA IF NOT EXISTS ECOM_ANALYTICS.MART;
CREATE SCHEMA IF NOT EXISTS ECOM_ANALYTICS.STAGING;

USE SCHEMA ECOM_ANALYTICS.MART;

CREATE TABLE IF NOT EXISTS DIM_PRODUCT (
    PRODUCT_SK        NUMBER        NOT NULL,
    PRODUCT_ID        VARCHAR       NOT NULL,
    SKU               VARCHAR,
    PRODUCT_NAME      VARCHAR,
    CATEGORY          VARCHAR,
    BRAND             VARCHAR,
    UNIT_PRICE        FLOAT,
    IS_ACTIVE         BOOLEAN       DEFAULT TRUE,
    EFFECTIVE_FROM    TIMESTAMP_TZ,
    EFFECTIVE_TO      TIMESTAMP_TZ,
    CONSTRAINT PK_DIM_PRODUCT PRIMARY KEY (PRODUCT_SK)
);

CREATE TABLE IF NOT EXISTS DIM_CUSTOMER (
    CUSTOMER_SK       NUMBER        NOT NULL,
    CUSTOMER_ID       VARCHAR       NOT NULL,
    EMAIL             VARCHAR,
    COUNTRY           VARCHAR,
    SEGMENT           VARCHAR,
    IS_ACTIVE         BOOLEAN       DEFAULT TRUE,
    EFFECTIVE_FROM    TIMESTAMP_TZ,
    EFFECTIVE_TO      TIMESTAMP_TZ,
    CONSTRAINT PK_DIM_CUSTOMER PRIMARY KEY (CUSTOMER_SK)
);

CREATE TABLE IF NOT EXISTS FACT_CLICKS (
    CLICK_SK          NUMBER,
    EVENT_ID          VARCHAR,
    EVENT_TYPE        VARCHAR,
    EVENT_TS          TIMESTAMP_TZ,
    SESSION_ID        VARCHAR,
    CUSTOMER_SK       NUMBER,
    CUSTOMER_ID       VARCHAR,
    PRODUCT_SK        NUMBER,
    PRODUCT_ID        VARCHAR,
    PAGE_URL          VARCHAR,
    SEARCH_QUERY      VARCHAR,
    QUANTITY          NUMBER,
    DEVICE            VARCHAR,
    COUNTRY           VARCHAR,
    REFERRER          VARCHAR
);

CREATE TABLE IF NOT EXISTS FACT_ORDERS (
    ORDER_SK          NUMBER,
    ORDER_ID          VARCHAR,
    EVENT_ID          VARCHAR,
    ORDER_TS          TIMESTAMP_TZ,
    CUSTOMER_SK       NUMBER,
    CUSTOMER_ID       VARCHAR,
    PRODUCT_SK        NUMBER,
    PRODUCT_ID        VARCHAR,
    QUANTITY          NUMBER,
    UNIT_PRICE        FLOAT,
    LINE_TOTAL        FLOAT,
    CURRENCY          VARCHAR,
    STATUS            VARCHAR,
    CHANNEL           VARCHAR
);

-- Example clustering for time-series scans (tune for workload).
ALTER TABLE FACT_CLICKS CLUSTER BY (DATE_TRUNC('DAY', EVENT_TS), EVENT_TYPE);
ALTER TABLE FACT_ORDERS CLUSTER BY (DATE_TRUNC('DAY', ORDER_TS));
